-- View ini membantu pengecekan stok di Supabase dan tidak dihitung sebagai entitas ERD.
create or replace view material_stock_summary as
select
  m.id,
  m.name,
  m.unit,
  m.minimum_stock,
  coalesce(sum(case when st.transaction_type = 'IN' then st.quantity else 0 end), 0)
    - coalesce(sum(case when st.transaction_type = 'OUT' then st.quantity else 0 end), 0) as current_stock
from materials m
left join stock_transactions st on st.material_id = m.id
group by m.id, m.name, m.unit, m.minimum_stock;

