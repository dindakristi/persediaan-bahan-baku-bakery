-- Bunberry Bakery - Supabase / PostgreSQL
-- ERD: suppliers 1--* materials 1--* stock_transactions

create table if not exists suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists material_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists materials (
  id bigint generated by default as identity primary key,
  name text not null,
  unit text not null check (unit in ('kg', 'gram', 'liter', 'ml', 'pcs')),
  minimum_stock numeric(12,2) not null default 0 check (minimum_stock >= 0),
  supplier_id bigint references suppliers(id) on delete set null,
  category_id bigint references material_categories(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table materials add column if not exists category_id bigint references material_categories(id) on delete set null;

create table if not exists stock_transactions (
  id bigint generated by default as identity primary key,
  material_id bigint not null references materials(id) on delete cascade,
  transaction_type text not null check (transaction_type in ('IN', 'OUT')),
  quantity numeric(12,2) not null check (quantity > 0),
  unit_price numeric(14,2) not null default 0 check (unit_price >= 0),
  notes text,
  transaction_date date not null default current_date,
  created_at timestamptz not null default now()
);

create table if not exists purchase_orders (
  id bigint generated by default as identity primary key,
  supplier_id bigint references suppliers(id) on delete set null,
  material_id bigint not null references materials(id) on delete restrict,
  quantity numeric(12,2) not null check (quantity > 0),
  unit_price numeric(14,2) not null default 0 check (unit_price >= 0),
  order_date date not null default current_date,
  status text not null default 'Dipesan' check (status in ('Dipesan', 'Diterima')),
  received_at date,
  created_at timestamptz not null default now()
);

create index if not exists materials_supplier_id_idx on materials(supplier_id);
create index if not exists materials_category_id_idx on materials(category_id);
create index if not exists stock_transactions_material_id_idx on stock_transactions(material_id);
create index if not exists stock_transactions_date_idx on stock_transactions(transaction_date desc);
create index if not exists purchase_orders_created_at_idx on purchase_orders(created_at desc);

