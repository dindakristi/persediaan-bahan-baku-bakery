create or replace function receive_purchase_order(p_order_id bigint)
returns void
language plpgsql
as $$
declare
  received_order purchase_orders%rowtype;
begin
  update purchase_orders
  set status = 'Diterima', received_at = current_date
  where id = p_order_id and status = 'Dipesan'
  returning * into received_order;

  if not found then
    raise exception 'Pesanan tidak ditemukan atau sudah diterima.';
  end if;

  insert into stock_transactions (material_id, transaction_type, quantity, unit_price, notes, transaction_date)
  values (
    received_order.material_id,
    'IN',
    received_order.quantity,
    received_order.unit_price,
    'Penerimaan pesanan #' || received_order.id,
    received_order.received_at
  );
end;
$$;

grant select, insert, update on purchase_orders to anon, authenticated;
grant execute on function receive_purchase_order(bigint) to anon, authenticated;

